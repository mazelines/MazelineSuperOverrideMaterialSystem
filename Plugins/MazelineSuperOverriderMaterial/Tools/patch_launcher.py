"""Generate a project-specific PowerShell entry point using bundled UE Python."""
from pathlib import Path

import shader_patch


def ps_literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def write_launcher(engine, project, output_dir):
    engine = Path(engine).resolve(strict=True)
    project = Path(project).resolve(strict=True)
    executable = engine / "Engine/Binaries/ThirdParty/Python3/Win64/python.exe"
    if not executable.is_file():
        raise RuntimeError("Unreal bundled Python executable is unavailable")
    manager = Path(__file__).resolve().with_name("manage_shader_patch.py")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    output = output_dir / "ManagePatch.ps1"
    code = "\n".join([
        "# Generated by Mazeline Super Overrider Material. Close this engine's editors before mutation.",
        "param([ValidateSet('status','apply','restore','recover')][string]$Action = 'status')",
        "$ErrorActionPreference = 'Stop'",
        "& " + ps_literal(executable) + " " + ps_literal(manager)
        + " $Action --engine " + ps_literal(engine) + " --project " + ps_literal(project),
        "if ($LASTEXITCODE -ne 0) { throw ('Mazeline patch operation failed: exit ' + $LASTEXITCODE) }",
        "",
    ])
    # Windows PowerShell 5.1 needs a BOM to reliably read non-ASCII project paths.
    shader_patch.atomic_write(output, code.encode("utf-8-sig"))
    return output
